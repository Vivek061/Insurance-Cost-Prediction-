import streamlit as st
import pandas as pd
import joblib

st.set_page_config(
    page_title="Insurance Cost Predictor",
    page_icon="💰",
    layout="centered"
)

insurance_pipeline = joblib.load("insurance_pipeline.pkl")

st.title("Insurance Cost Prediction")
st.write(
    "Enter a customer's information to estimate their medical insurance cost."
)
st.subheader("Enter Customer Details")

with st.form("prediction_form"):
    age = st.number_input(
        "Age",
        min_value=18,
        max_value=64,
        value=30,
        step=1
    )

    sex = st.selectbox(
        "Sex",
        options=["female", "male"]
    )

    bmi = st.number_input(
        "BMI",
        min_value=15.0,
        max_value=55.0,
        value=25.0,
        step=0.1
    )

    children = st.number_input(
        "Number of Children",
        min_value=0,
        max_value=5,
        value=0,
        step=1
    )

    smoker = st.selectbox(
        "Smoker",
        options=["no", "yes"]
    )

    region = st.selectbox(
        "Region",
        options=[
            "northeast",
            "northwest",
            "southeast",
            "southwest"
        ]
    )

    predict_button = st.form_submit_button(
        "Predict Insurance Cost"
    )

if predict_button:
    customer_data = pd.DataFrame({
        "age": [age],
        "sex": [sex],
        "bmi": [bmi],
        "children": [children],
        "smoker": [smoker],
        "region": [region]
    })

    prediction = insurance_pipeline.predict(customer_data)[0]

    st.success("Prediction completed successfully!")
    st.metric(
        label="Estimated Insurance Charges",
        value=f"{prediction:,.2f}"
    )

    st.caption(
        "This prediction is an estimate generated by a machine-learning model."
    )
